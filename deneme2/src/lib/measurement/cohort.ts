/**
 * Builds a comparison cohort from a single starting company.
 *
 * Flow: analyse the target -> work out what it is -> name comparable
 * institutions -> for each, find the page that plays the same role -> put it
 * through the same acceptance gate -> analyse it -> compute distributions.
 *
 * The acceptance gate is the whole point. An irrelevant or broken page that
 * slips into the cohort does not just add noise: it enters the denominator and
 * makes every percentage wrong. So a candidate is accepted only when
 *   - its homepage loads
 *   - an equivalent page is found among its REAL links
 *   - that page passes the capture quality gate
 *   - its content actually relates to the target topic
 * and every rejection is recorded with a reason instead of disappearing.
 */
import { PrismaClient, type ObservationStatus, type PageRole } from "@prisma/client";
import { analyze } from "./analyze";
import { capturePage } from "./capture";
import {
  absoluteUrl,
  homepageUrl,
  identifyTarget,
  proposePeers,
  resolveEquivalentFromSitemap,
  resolveEquivalentPage,
  type TargetIdentity,
} from "./peer-discovery";
import { generateSectorCatalogue } from "./catalogue-generation";
import { distribution, MIN_DENOMINATOR_FOR_PERCENT } from "./patterns";

const prisma = new PrismaClient();

export interface PeerOutcome {
  institution: string;
  domain: string;
  equivalentUrl: string | null;
  accepted: boolean;
  reason: string;
  benchmarkId?: string;
}

export interface CriterionDistribution {
  code: string;
  /** Stable function identity - this is what makes cross-sector reuse possible. */
  featureId: string | null;
  question: string;
  pattern: string;
  denominator: number;
  rows: Array<{ value: string; count: number; percent: number | null }>;
  excluded: { unknown: number; notApplicable: number };
  /**
   * Prevalence and coverage are different numbers and must both be shown.
   * "28 of 40 measurable institutions have it (70%)" is a finding.
   * "only 40 of 50 could be measured (80%)" is how much to trust it.
   * Reporting the first without the second overstates the result.
   */
  coverage: { measured: number; cohortSize: number; percent: number | null };
  targetValue: string | null;
  targetStatus: ObservationStatus | null;
}

export interface CohortRunResult {
  identity: TargetIdentity | null;
  targetBenchmarkId: string;
  cohortId: string | null;
  peers: PeerOutcome[];
  distributions: CriterionDistribution[];
  percentagesWithheld: boolean;
  /** How many proposed institutions actually made it into the cohort. */
  cohortCoverage: { accepted: number; proposed: number; percent: number };
  /**
   * Set only when this run is the FIRST analysis ever done for this sector -
   * its catalogue was just generated by a model and validated, not
   * hand-authored or previously reviewed. Null means an existing, already
   * materialised catalogue was reused.
   */
  generatedCatalogue: {
    criteriaCount: number;
    rejectedCount: number;
    rejectedReasons: string[];
  } | null;
}

/** Cheap page-type check: does the peer page actually talk about the topic? */
function topicMatches(topic: string, text: string): boolean {
  const fold = (s: string) =>
    s.replace(/[İIı]/g, "i").toLowerCase().replace(/̇/g, "");
  const tokens = fold(topic)
    .split(/[^a-z0-9çğöşü]+/)
    .filter((t) => t.length >= 4);
  if (tokens.length === 0) return true;
  const haystack = fold(text);
  return tokens.some((t) => haystack.includes(t));
}

export async function buildPeerCohort(options: {
  url: string;
  viewport?: "DESKTOP" | "MOBILE";
  peerCount?: number;
  sectorSlug?: string;
}): Promise<CohortRunResult> {
  const viewport = options.viewport ?? "DESKTOP";
  // 10 minimum: below 8 no percentage can be shown, and a few candidates are
  // always lost to the acceptance gate. Asking for 10 usually leaves enough.
  const peerCount = options.peerCount ?? 10;

  // ---- 1. Target ----
  const probe = await capturePage({ url: options.url, viewport });
  if (!probe.snapshot) {
    throw new Error(`target capture failed: ${probe.status} ${probe.error ?? ""}`);
  }
  const identity = await identifyTarget(probe.snapshot);
  if (!identity) throw new Error("could not identify the target page");

  const sectorSlug = options.sectorSlug ?? identity.sectorSlug;
  const sector = await prisma.sector.upsert({
    where: { slug: sectorSlug },
    update: {},
    create: { slug: sectorSlug, name: identity.sectorName, country: identity.country },
  });

  // Is this sector already known? If not, there is no fixed list of sectors
  // to fall back on - the whole point is that a user can drop in a page from
  // any industry and get a real comparison, not just the ones someone sat
  // down and catalogued in advance. So an unknown sector's catalogue is
  // generated right now, validated, and persisted before anything else runs -
  // same discipline as everywhere else: the model proposes, the software
  // decides what actually gets saved.
  let pkg = await prisma.criteriaPackage.findFirst({
    where: { sectorId: sector.id },
    orderBy: { createdAt: "desc" },
  });
  let catalogueGenerated: Awaited<ReturnType<typeof generateSectorCatalogue>> | null = null;
  if (!pkg) {
    catalogueGenerated = await generateSectorCatalogue(identity);
    pkg = await prisma.criteriaPackage.findUnique({ where: { id: catalogueGenerated.packageId } });
    if (!pkg) throw new Error("üretilen katalog kalıcı hale getirilemedi");
  }

  const targetRun = await analyze({
    url: options.url,
    viewport,
    institution: identity.institution,
    sectorSlug,
  });

  // ---- 2. Peers ----
  const candidates = await proposePeers(identity, peerCount);
  const outcomes: PeerOutcome[] = [];
  const acceptedBenchmarks: Array<{ institution: string; benchmarkId: string }> = [];

  for (const candidate of candidates) {
    const home = homepageUrl(candidate.domain);
    const base: PeerOutcome = {
      institution: candidate.institution,
      domain: candidate.domain,
      equivalentUrl: null,
      accepted: false,
      reason: "",
    };

    const homeCapture = await capturePage({ url: home, viewport });
    if (!homeCapture.snapshot || homeCapture.status !== "SUCCESS") {
      outcomes.push({ ...base, reason: `homepage not reachable (${homeCapture.status})` });
      continue;
    }

    let equivalentUrl: string;
    let foundVia: string;

    if (identity.pageRole === "ENTRY") {
      // The target itself was a homepage - there is no "sub-page about the
      // topic" to go looking for, the topic IS the homepage. Searching
      // navigation/sitemap for a link matching a topic like "online shopping
      // homepage" finds nothing on a real site (nobody links to their own
      // homepage with that label), which was silently dropping 3 of 4 peers
      // for every ENTRY-role cohort. The peer's homepage is simply the
      // equivalent page, full stop.
      equivalentUrl = homeCapture.finalUrl ?? home;
      foundVia = "homepage (ENTRY role, no sub-page search needed)";
      if (homeCapture.quality?.passed !== true) {
        const failed = homeCapture.quality
          ? Object.entries(homeCapture.quality.checks)
              .filter(([, c]) => !c.passed)
              .map(([n]) => n)
              .join(", ")
          : homeCapture.status;
        outcomes.push({ ...base, equivalentUrl, reason: `quality gate failed (${failed})` });
        continue;
      }
    } else {
      // Navigation first, sitemap second. A page that exists but is not
      // linked from the home page is still a real page - one bank was
      // wrongly dropped from an earlier cohort for exactly this reason.
      let link = await resolveEquivalentPage(homeCapture.snapshot, identity);
      foundVia = "navigation";
      if (!link) {
        const origin = new URL(homeCapture.finalUrl ?? home).origin;
        link = await resolveEquivalentFromSitemap(origin, identity);
        foundVia = "sitemap";
      }
      if (!link) {
        outcomes.push({
          ...base,
          reason: "no equivalent page found in navigation or sitemap",
        });
        continue;
      }

      const resolved = absoluteUrl(link.href, homeCapture.finalUrl ?? home);
      if (!resolved) {
        outcomes.push({ ...base, reason: "equivalent link could not be resolved" });
        continue;
      }
      equivalentUrl = resolved;
      base.equivalentUrl = equivalentUrl;

      const peerProbe = await capturePage({ url: equivalentUrl, viewport });
      if (!peerProbe.snapshot || peerProbe.quality?.passed !== true) {
        const failed = peerProbe.quality
          ? Object.entries(peerProbe.quality.checks)
              .filter(([, c]) => !c.passed)
              .map(([n]) => n)
              .join(", ")
          : peerProbe.status;
        outcomes.push({ ...base, reason: `quality gate failed (${failed})` });
        continue;
      }

      if (!topicMatches(identity.pageTopic, peerProbe.snapshot.visibleText)) {
        outcomes.push({
          ...base,
          reason: `page does not relate to "${identity.pageTopic}"`,
        });
        continue;
      }
    }
    base.equivalentUrl = equivalentUrl;

    const run = await analyze({
      url: equivalentUrl,
      viewport,
      institution: candidate.institution,
      sectorSlug,
    });

    outcomes.push({
      ...base,
      accepted: true,
      reason: `accepted (via ${foundVia})`,
      benchmarkId: run.benchmarkId,
    });
    acceptedBenchmarks.push({
      institution: candidate.institution,
      benchmarkId: run.benchmarkId,
    });
  }

  // ---- 3. Cohort ----
  const cohort = await prisma.cohort.upsert({
    where: {
      sectorId_pageRole_viewport_country_version: {
        sectorId: sector.id,
        pageRole: identity.pageRole as PageRole,
        viewport,
        country: identity.country,
        version: "v1",
      },
    },
    update: { packageId: pkg.id },
    create: {
      sectorId: sector.id,
      pageRole: identity.pageRole as PageRole,
      viewport,
      country: identity.country,
      version: "v1",
      packageId: pkg.id,
    },
  });

  // One row per institution: the unique key makes five captures of the same
  // bank impossible to count as five banks.
  //
  // The target itself is a member too, not just the institutions it was
  // compared against. Leaving it out would mean the one page a user actually
  // submitted - the one whose detail view they open first - can never find
  // its own peers, because peer lookup elsewhere keys off cohort membership.
  for (const m of [...acceptedBenchmarks, { institution: identity.institution, benchmarkId: targetRun.benchmarkId }]) {
    await prisma.cohortMember.upsert({
      where: { cohortId_institution: { cohortId: cohort.id, institution: m.institution } },
      update: { benchmarkId: m.benchmarkId },
      create: {
        cohortId: cohort.id,
        institution: m.institution,
        benchmarkId: m.benchmarkId,
      },
    });
  }

  // ---- 4. Distributions ----
  const memberIds = acceptedBenchmarks.map((m) => m.benchmarkId);
  const criteria = await prisma.criterion.findMany({
    where: { packages: { some: { packageId: pkg.id } } },
    orderBy: { code: "asc" },
  });

  const peerObservations = memberIds.length
    ? await prisma.observation.findMany({
        where: { benchmarkId: { in: memberIds }, packageId: pkg.id },
        select: { criterionId: true, value: true, status: true, awaitingConfirmation: true },
      })
    : [];

  const targetObservations = await prisma.observation.findMany({
    where: { benchmarkId: targetRun.benchmarkId, packageId: pkg.id },
    select: { criterionId: true, value: true, status: true },
  });
  const targetByCriterion = new Map(targetObservations.map((o) => [o.criterionId, o]));

  const distributions: CriterionDistribution[] = criteria.map((c) => {
    // An observation still awaiting model confirmation is not published, so it
    // must not reach the denominator either.
    const rows = peerObservations
      .filter((o) => o.criterionId === c.id && !o.awaitingConfirmation)
      .map((o) => ({ value: o.value, status: o.status }));
    const d = distribution(rows);
    const t = targetByCriterion.get(c.id);
    const cohortSize = acceptedBenchmarks.length;
    return {
      code: c.code,
      featureId: c.featureId,
      question: c.question,
      pattern: c.pattern,
      denominator: d.denominator,
      rows: d.rows,
      excluded: d.excluded,
      coverage: {
        measured: d.denominator,
        cohortSize,
        percent: cohortSize === 0 ? null : Math.round((d.denominator / cohortSize) * 100),
      },
      targetValue: t?.value ?? null,
      targetStatus: t?.status ?? null,
    };
  });

  return {
    identity,
    targetBenchmarkId: targetRun.benchmarkId,
    cohortId: cohort.id,
    peers: outcomes,
    distributions,
    percentagesWithheld: acceptedBenchmarks.length < MIN_DENOMINATOR_FOR_PERCENT,
    cohortCoverage: {
      accepted: acceptedBenchmarks.length,
      proposed: candidates.length,
      percent:
        candidates.length === 0
          ? 0
          : Math.round((acceptedBenchmarks.length / candidates.length) * 100),
    },
    generatedCatalogue: catalogueGenerated
      ? {
          criteriaCount: catalogueGenerated.criteriaCount,
          rejectedCount: catalogueGenerated.rejected.length,
          rejectedReasons: catalogueGenerated.rejected.map((r) => r.reason),
        }
      : null,
  };
}

export { prisma as cohortPrisma };
